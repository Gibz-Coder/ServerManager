def _safe_int(v):
    try: return int(float(v)) if v not in (None, '') else None
    except: return None

def _safe_float(v):
    try: return float(v) if v not in (None, '') else None
    except: return None

def _safe_str(v, maxlen=128):
    if v in (None, ''): return None
    return str(v)[:maxlen]

def _s(row, key, maxlen=128):
    return _safe_str(row.get(key), maxlen)

def _i(row, key):
    return _safe_int(row.get(key))

def _f(row, key):
    return _safe_float(row.get(key))


